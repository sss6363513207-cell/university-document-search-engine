export class Engine2Error extends Error {
  constructor(code, message, details = {}) {
    super(message);

    this.name = "Engine2Error";
    this.code = code;
    this.details = details;
  }

  toJSON() {
    return {
      success: false,
      error: {
        code: this.code,
        message: this.message,
        ...this.details
      }
    };
  }
}

